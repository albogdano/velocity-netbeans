package com.erudika.netbeans.velocity.parser;

import java.util.Collection;
import java.util.Collections;
import org.netbeans.modules.parsing.api.Snapshot;
import org.netbeans.modules.parsing.spi.SchedulerTask;
import org.netbeans.modules.parsing.spi.TaskFactory;

/**
 * Creates a {@link VTLMacroValidationTask} for given source.
 */
public class VTLMacroValidationTaskFactory extends TaskFactory {

	public VTLMacroValidationTaskFactory() {
	}

	@Override
	public Collection<? extends SchedulerTask> create(final Snapshot snapshot) {
		return Collections.singleton(new VTLMacroValidationTask());
	}
}